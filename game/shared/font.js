const GLYPHS = {};
for (const [ch, raw] of Object.entries(RAW)) {
  const rows = raw.split('/');
  if (rows.length !== 7 || rows.some(r => r.length !== 5)) throw new Error(`glifo inválido: ${ch}`);
  GLYPHS[ch] = rows;
}
const ALIAS = { '—': '-', '–': '-', '’': "'", '›': '>', '‹': '<', '•': '·' };
// marcas combinantes: [linha relativa ao topo do glifo, pixels]
const MARKS = {
  '́': [[-2, '...#.'], [-1, '..#..']], // agudo
  '̀': [[-2, '.#...'], [-1, '..#..']], // grave
  '̂': [[-2, '..#..'], [-1, '.#.#.']], // circunflexo
  '̃': [[-2, '.##.#'], [-1, '#..#.']], // til
  '̧': [[7, '..#..'], [8, '.##..']],   // cedilha
};

export const CHAR_W = 6;   // avanço por caractere
export const LINE_H = 11;  // altura de linha (com espaço para acentos e cedilha)

const chars = str => [...String(str).toUpperCase().normalize('NFD')];
export const textLength = str => chars(str).filter(c => !MARKS[c]).length;
export const textWidth = (str, scale = 1) => (textLength(str) * CHAR_W - 1) * scale;

// Retorna retângulos [x, y, w, h, cor] do texto com o canto superior esquerdo do primeiro glifo em (x, y).
export function textRects(str, x, y, color, scale = 1, maxChars = Infinity) {
  const out = [];
  const row = (pixels, cx, cy) => {
    for (let i = 0; i < 5; i++) {
      if (pixels[i] !== '#') continue;
      let n = 1; while (i + n < 5 && pixels[i + n] === '#') n++;
      out.push([x + (cx + i) * scale, y + cy * scale, n * scale, scale, color]);
      i += n;
    }
  };
  let col = -1;
  for (const raw of chars(str)) {
    if (MARKS[raw]) { if (col >= 0 && col < maxChars) for (const [dy, px] of MARKS[raw]) row(px, col * CHAR_W, dy); continue; }
    col++;
    if (col >= maxChars) break;
    const ch = ALIAS[raw] || raw;
    if (ch === ' ') continue;
    (GLYPHS[ch] || GLYPHS['?']).forEach((px, gy) => row(px, col * CHAR_W, gy));
  }
  return out;
}

// Texto com sombra de 1 px (escala incluída).
export function shadowText(str, x, y, color, scale = 1, shadow = '#14101a') {
  return [...textRects(str, x + scale, y + scale, shadow, scale), ...textRects(str, x, y, color, scale)];
}
